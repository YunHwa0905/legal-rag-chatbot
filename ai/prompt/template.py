"""
나이대별 프롬프트 템플릿

역할:
- 사용자 나이에 따라 설명 난이도 조절
- 법률 컨텍스트 + 나이대별 말투 조합
"""

# ===========================
# 나이대 구분
# ===========================
def get_age_group(age: int) -> str:
    if age <= 10:
        return "child"       # 어린이 (10세 이하)
    elif age <= 19:
        return "teen"        # 청소년 (11~19세)
    elif age <= 40:
        return "adult"       # 성인 (20~40세)
    else:
        return "senior"      # 중장년 (41세 이상)


