# ===========================
# 프롬프트 빌더
# ===========================
def build_prompt(
    question: str,
    context: str,
    age: int,
) -> dict:
    """
    Args:
        question: 사용자 질문
        context: RAG 검색 결과 텍스트
        age: 사용자 나이

    Returns:
        {
            "system": 시스템 프롬프트,
            "user": 유저 메시지,
            "age_group": 나이대,
            "age_group_label": 나이대 레이블 (UI용)
        }
    """
    age_group = get_age_group(age)
    system_prompt = SYSTEM_PROMPTS[age_group]

    user_message = f"""[참고 문서]
{context}

[질문]
{question}"""

    return {
        "system": system_prompt,
        "user": user_message,
        "age_group": age_group,
        "age_group_label": AGE_GROUP_LABEL[age_group],
    }


# ===========================
# 테스트
# ===========================
def test():
    question = "계약서에 도장 안 찍으면 어떻게 되나요?"
    context = """[문서 1] (민사법 - 법령)
민법 제563조에 따르면 매매계약은 당사자 일방이 재산권을 상대방에게 이전할 것을 약정하고,
상대방이 그 대금을 지급할 것을 약정함으로써 효력이 생긴다.
계약은 원칙적으로 당사자 간의 합의만으로 성립하며, 서면이나 날인이 필수 요건은 아니다."""

    test_ages = [8, 15, 25, 55]

    for age in test_ages:
        print(f"\n{'='*50}")
        print(f"나이: {age}세")
        print(f"{'='*50}")

        prompt = build_prompt(question, context, age)
        print(f"나이대: {prompt['age_group_label']}")
        print(f"\n[시스템 프롬프트 앞부분]")
        print(prompt["system"][:100] + "...")
        print(f"\n[유저 메시지 앞부분]")
        print(prompt["user"][:150] + "...")


if __name__ == "__main__":
    test()