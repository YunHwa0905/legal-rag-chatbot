#!/usr/bin/env bash
# ===========================================================
# 서버에서 실행되는 배포 스크립트
#
# 수동 실행:
#   bash deploy/remote-deploy.sh
#
# GitHub Actions 에서도 이 스크립트를 SSH 로 흘려보내 실행합니다
# (.github/workflows/deploy.yml).
# 배포 로직을 워크플로 YAML 안에 인라인으로 쓰지 않는 이유는,
# 자동 배포가 실패했을 때 서버에서 같은 스크립트를 손으로 돌려
# 원인을 분리할 수 있게 하기 위해서입니다.
# ===========================================================

set -euo pipefail

APP_DIR="${APP_DIR:-$HOME/legal-rag-chatbot}"

cd "$APP_DIR"

echo "==========================================================="
echo " 1. 코드 갱신"
echo "==========================================================="
git fetch --prune origin
# --ff-only: 서버에서 직접 커밋한 게 있으면 조용히 덮어쓰지 않고 실패합니다.
git pull --ff-only origin main

echo "==========================================================="
echo " 2. .env 존재 확인"
echo "==========================================================="
if [ ! -f .env ]; then
    echo "[FATAL] .env 가 없습니다. .env.example 을 복사해 작성하세요." >&2
    exit 1
fi

echo "==========================================================="
echo " 3. 이미지 빌드 (직접 만드는 서비스만)"
echo "==========================================================="
# 코드나 정적 파일이 바뀌었으면 반드시 재빌드해야 반영됩니다.
docker compose build ai frontend tomcat

echo "==========================================================="
echo " 4. 컨테이너 재생성"
echo "==========================================================="
# up -d 는 설정(이미지·환경변수)이 바뀐 컨테이너만 재생성합니다.
# restart 로는 새 환경변수가 반영되지 않으므로 항상 up -d 를 씁니다.
# opensearch / ollama / mysql 은 변경이 없으면 그대로 유지되며
# 볼륨(인덱스·모델·DB)은 어떤 경우에도 건드리지 않습니다.
docker compose up -d

echo "==========================================================="
echo " 5. 정리 및 상태"
echo "==========================================================="
docker image prune -f
docker compose ps

echo
echo "[DONE] 배포 완료. 애플리케이션 로그:"
echo "  docker compose logs -f --tail=100 ai tomcat"
